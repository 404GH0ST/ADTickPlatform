#!/usr/bin/env node
/**
 * Discovers theme folders under apps/web/themes/ and writes:
 *   themes/registry.generated.ts   imports every themes/<id>/theme.ts
 *   themes/themes.generated.css    @imports every themes/<id>/theme.css
 *
 * A folder is a theme when it contains theme.ts; folders starting with "_"
 * or "." are skipped. The default theme (graphite) is always emitted first so
 * its bare :root tokens act as the fallback for every other theme.
 *
 * It also writes themes/fixtures.generated.ts (gitignored). That file is
 * empty unless AD_PLATFORM_THEME_FIXTURES=1, in which case it registers the
 * test-only themes in themes/_fixtures/<id>/ (used by the e2e build, e.g. a
 * theme whose views crash on purpose). Fixtures never reach a normal build.
 *
 * Usage: node scripts/generate-themes.mjs [--check]
 *   --check  exit 1 if the generated files are stale (for CI / tests)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_THEME_ID = "graphite";
const ID_PATTERN = /^[a-z0-9][a-z0-9-]{0,47}$/;
const themesDir = join(dirname(fileURLToPath(import.meta.url)), "..", "themes");

export function discoverThemes(dir = themesDir) {
  const ids = readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !/^[_.]/.test(entry.name))
    .map((entry) => entry.name)
    .filter((name) => existsSync(join(dir, name, "theme.ts")));
  for (const id of ids) {
    if (!ID_PATTERN.test(id)) {
      throw new Error(`themes/${id}: folder name must be a lowercase slug (a-z, 0-9, -), at most 48 chars`);
    }
  }
  if (!ids.includes(DEFAULT_THEME_ID)) {
    throw new Error(`themes/${DEFAULT_THEME_ID} (the default theme) is missing`);
  }
  ids.sort((a, b) => (a === DEFAULT_THEME_ID ? -1 : b === DEFAULT_THEME_ID ? 1 : a.localeCompare(b)));
  return ids;
}

export function discoverFixtureThemes(dir = themesDir) {
  const fixturesDir = join(dir, "_fixtures");
  if (!existsSync(fixturesDir)) return [];
  return readdirSync(fixturesDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(join(fixturesDir, entry.name, "theme.ts")))
    .map((entry) => entry.name)
    .sort();
}

export function renderFixtures(ids) {
  const header = "// AUTO-GENERATED by scripts/generate-themes.mjs (gitignored). Test-only themes; empty unless AD_PLATFORM_THEME_FIXTURES=1.\n";
  const imports = ids.map((id) => `import ${identifier(id)} from "./_fixtures/${id}/theme";`).join("\n");
  const list = ids.map((id) => `  ${identifier(id)},`).join("\n");
  return `${header}import type { ThemeDefinition } from "@/lib/theme-contract";\n${imports ? `\n${imports}\n` : ""}\nexport const FIXTURE_THEMES: readonly ThemeDefinition[] = [${list ? `\n${list}\n` : ""}];\n`;
}

function identifier(id) {
  return `theme_${id.replace(/-/g, "_")}`;
}

export function renderRegistry(ids) {
  const header = "// AUTO-GENERATED by scripts/generate-themes.mjs. Do not edit; add a themes/<id>/ folder instead.\n";
  const imports = ids.map((id) => `import ${identifier(id)} from "./${id}/theme";`).join("\n");
  const list = ids.map((id) => `  ${identifier(id)},`).join("\n");
  return `${header}import type { ThemeDefinition } from "@/lib/theme-contract";\n\n${imports}\n\nexport const GENERATED_THEMES: readonly ThemeDefinition[] = [\n${list}\n];\n`;
}

export function renderCss(ids, dir = themesDir) {
  const header = "/* AUTO-GENERATED by scripts/generate-themes.mjs. Do not edit; add a themes/<id>/ folder instead. */\n";
  const imports = ids
    .filter((id) => existsSync(join(dir, id, "theme.css")))
    .map((id) => `@import "./${id}/theme.css";`)
    .join("\n");
  return `${header}${imports}\n`;
}

function main() {
  const check = process.argv.includes("--check");
  const ids = discoverThemes();
  const outputs = [
    [join(themesDir, "registry.generated.ts"), renderRegistry(ids)],
    [join(themesDir, "themes.generated.css"), renderCss(ids)],
  ];
  let stale = false;
  for (const [path, content] of outputs) {
    const current = existsSync(path) ? readFileSync(path, "utf8") : "";
    if (current === content) continue;
    stale = true;
    if (!check) writeFileSync(path, content);
  }
  if (check && stale) {
    console.error("Theme registry is stale. Run: bun run themes");
    process.exit(1);
  }
  // Fixtures are environment-dependent, so they are written but never checked.
  const fixtureIds = process.env.AD_PLATFORM_THEME_FIXTURES === "1" ? discoverFixtureThemes() : [];
  const fixturesPath = join(themesDir, "fixtures.generated.ts");
  const fixtures = renderFixtures(fixtureIds);
  if (!existsSync(fixturesPath) || readFileSync(fixturesPath, "utf8") !== fixtures) {
    writeFileSync(fixturesPath, fixtures);
  }
  if (!check) {
    console.log(`themes: ${ids.join(", ")}${fixtureIds.length ? ` (+ test fixtures: ${fixtureIds.join(", ")})` : ""}`);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main();
}
